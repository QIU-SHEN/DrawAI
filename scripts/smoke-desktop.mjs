import { exampleDocument } from '../tests/fixtures/example.mjs';
import { _electron as electron, expect } from '@playwright/test';
import { mkdir, mkdtemp, copyFile, readFile, writeFile } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import path from 'node:path';
import assert from 'node:assert/strict';
const base = path.resolve('.local/desktop-smoke'); await mkdir(base, { recursive: true });
const dir = await mkdtemp(path.join(base, '运行 中文 '));
const exe = path.resolve('releases/DrawAI-0.7.0/DrawAI-win32-x64/DrawAI.exe');
const file = path.join(dir, '第一张 图.drawai'), secondFile = path.join(dir, '第二张 图.drawai');
await writeFile(file, JSON.stringify({ format: 'drawai', version: 1, workspaceName: '测试图表', document: exampleDocument(), view: { mode: 'spatial' } })); await copyFile(file, secondFile);
const env = { ...process.env, TEMP: dir, TMP: dir }; delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ executablePath: exe, args: [file], env });
try {
  const page = await app.firstWindow(); await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().forEach(w => w.hide()));
  await expect(page.locator('#desktop-save')).toBeVisible(); await expect(page.locator('#save-status')).toHaveText('已保存到文件');
  assert.equal(await app.evaluate(({ app }) => app.isPackaged), true);
  assert.equal(await app.evaluate(({ app }) => app.getPath('userData')), path.join(path.dirname(exe), 'data'));
  await page.locator('#view-flat').click();
  await page.locator('[data-node]').first().dblclick(); await page.locator('#inline-node-title').fill('免安装 EXE 保存验证'); await page.locator('#inline-node-title').press('Enter');
  await expect(page.locator('#save-status')).toHaveText('有未保存的修改');
  await page.locator('#desktop-save').click();
  await expect(page.locator('#save-status')).toHaveText('已保存到文件');
  assert.equal(JSON.parse(await readFile(file, 'utf8')).document.nodes[0].title, '免安装 EXE 保存验证');
  const exported = path.join(dir, '桌面导出.drawai');
  await app.evaluate(({ dialog }, filename) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: filename }); }, exported);
  await page.locator('#export').click(); await expect(page.locator('#toast')).toContainText('已导出 .drawai');
  assert.equal(JSON.parse(await readFile(exported, 'utf8')).document.nodes[0].title, '免安装 EXE 保存验证');
  await expect(page.locator('#save-status')).toHaveAttribute('title', file);
  const child = promisify(execFile)(exe, [secondFile], { env, windowsHide: true, timeout: 30000 });
  await expect.poll(async () => (await app.windows()).length, { timeout: 30000 }).toBe(2); await child;
  const next = (await app.windows()).find(p => p !== page); await expect(next.locator('#desktop-save')).toBeVisible();
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().forEach(w => w.hide()));
  await promisify(execFile)(exe, [secondFile], { env, windowsHide: true, timeout: 30000 });
  assert.equal((await app.windows()).length, 2);
  const firstWindow = await app.browserWindow(page); await firstWindow.evaluate(win => { win.show(); win.focus(); });
  await page.screenshot({ path: path.resolve('releases/desktop-preview.png') });
  console.log('PACKAGED PASS: native opening, in-place save, DrawAI file export, actual second process, duplicate-file focus.');
} finally { await app.evaluate(({ app }) => app.exit(0)).catch(() => {}); }
